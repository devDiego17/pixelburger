-- Registro inicial del perfil (una sola vez por cuenta)
create or replace function public.complete_signup(
  p_display_name text, p_alias text, p_whatsapp text, p_barrio text,
  p_adult boolean, p_consent_data boolean, p_consent_marketing boolean, p_referral_qr text default null)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_uid uuid := auth.uid();
  v_ref uuid;
  v_no integer;
begin
  if v_uid is null then raise exception 'NO_AUTENTICADO' using errcode = '28000'; end if;
  perform app_private.rate_limit('signup:' || v_uid, 10, 3600);
  if exists (select 1 from public.profiles where id = v_uid) then raise exception 'PERFIL_YA_EXISTE' using errcode = '23505'; end if;
  if not coalesce(p_adult, false) then raise exception 'DEBES_SER_MAYOR_DE_EDAD' using errcode = '22023'; end if;
  if not coalesce(p_consent_data, false) then raise exception 'FALTA_AUTORIZACION_DATOS' using errcode = '22023'; end if;
  if exists (select 1 from public.profiles where lower(alias) = lower(trim(p_alias))) then raise exception 'ALIAS_OCUPADO' using errcode = '23505'; end if;

  if p_referral_qr is not null and length(trim(p_referral_qr)) > 0 then
    select id into v_ref from public.profiles
     where (qr_token = trim(p_referral_qr) or player_no::text = ltrim(trim(p_referral_qr), '#0'))
       and deleted_at is null;
  end if;

  insert into public.profiles (id, display_name, alias, whatsapp, barrio, adult_confirmed, consent_data_at, consent_marketing, referred_by)
  values (v_uid, trim(p_display_name), trim(p_alias), nullif(regexp_replace(coalesce(p_whatsapp, ''), '\D', '', 'g'), ''), nullif(trim(p_barrio), ''),
          true, now(), coalesce(p_consent_marketing, false), v_ref)
  returning player_no into v_no;

  perform app_private.grant_xp(v_uid, coalesce((app_private.setting('xp')->>'signup')::int, 100), 'signup', 'signup');
  return jsonb_build_object('player_no', v_no);
end $$;

create or replace function public.update_my_profile(p_display_name text, p_whatsapp text, p_barrio text, p_consent_marketing boolean)
returns void language plpgsql security definer set search_path = public, pg_temp as $$
declare v public.profiles := app_private.current_profile();
begin
  perform app_private.rate_limit('profile:' || v.id, 20, 3600);
  update public.profiles set
    display_name = trim(p_display_name),
    whatsapp = nullif(regexp_replace(coalesce(p_whatsapp, ''), '\D', '', 'g'), ''),
    barrio = nullif(trim(p_barrio), ''),
    consent_marketing = coalesce(p_consent_marketing, false)
  where id = v.id;
end $$;

