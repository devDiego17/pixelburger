-- =====================================================================
-- Pixel Burger · Plataforma de clientes
-- Modelo de seguridad:
--   * Ninguna tabla se escribe directamente desde la app. Todo cambio pasa
--     por funciones del servidor (SECURITY DEFINER) que validan quién llama,
--     qué puede hacer y con qué límites.
--   * La XP y las fichas viven en libros contables de solo inserción
--     (xp_ledger, ficha_ledger) con claves de idempotencia: un mismo evento
--     nunca suma dos veces.
--   * Row Level Security en todas las tablas: cada cliente solo lee lo suyo.
--   * Acciones del personal quedan en audit_log.
-- =====================================================================

create schema if not exists app_private;

-- ---------------------------------------------------------------------
-- Configuración editable sin tocar código
-- ---------------------------------------------------------------------
create table public.settings (
  key        text primary key,
  value      jsonb not null,
  updated_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- Perfiles
-- ---------------------------------------------------------------------
create table public.profiles (
  id                uuid primary key references auth.users(id) on delete cascade,
  player_no         integer generated by default as identity unique,
  display_name      text not null check (char_length(display_name) between 2 and 60),
  alias             text not null check (alias ~ '^[A-Za-z0-9_]{3,20}$'),
  whatsapp          text check (whatsapp ~ '^3[0-9]{9}$'),
  barrio            text check (char_length(barrio) <= 60),
  adult_confirmed   boolean not null default false,
  consent_data_at   timestamptz,
  consent_marketing boolean not null default false,
  referred_by       uuid references public.profiles(id),
  role              text not null default 'customer' check (role in ('customer', 'staff', 'admin')),
  qr_token          text not null unique default replace(gen_random_uuid()::text, '-', ''),
  created_at        timestamptz not null default now(),
  deleted_at        timestamptz
);
create unique index profiles_alias_lower on public.profiles (lower(alias));

-- ---------------------------------------------------------------------
-- Libros de XP y de fichas (solo inserción, idempotentes)
-- ---------------------------------------------------------------------
create table public.xp_ledger (
  id         bigint generated always as identity primary key,
  user_id    uuid not null references public.profiles(id) on delete cascade,
  amount     integer not null check (amount between -100000 and 100000 and amount <> 0),
  reason     text not null check (reason in ('signup', 'purchase', 'extra_burger', 'montanera_bonus', 'referral', 'code', 'game', 'album', 'admin_adjust')),
  ref        text not null,
  created_by uuid,
  created_at timestamptz not null default now(),
  unique (user_id, reason, ref)
);
create index xp_ledger_user_time on public.xp_ledger (user_id, created_at);

create table public.ficha_ledger (
  id         bigint generated always as identity primary key,
  user_id    uuid not null references public.profiles(id) on delete cascade,
  delta      integer not null check (delta between -100 and 100 and delta <> 0),
  reason     text not null check (reason in ('purchase', 'game', 'admin_adjust', 'welcome')),
  ref        text not null,
  created_by uuid,
  created_at timestamptz not null default now(),
  unique (user_id, reason, ref)
);
create index ficha_ledger_user on public.ficha_ledger (user_id);

-- ---------------------------------------------------------------------
-- Niveles y recompensas
-- ---------------------------------------------------------------------
create table public.levels (
  level   integer primary key,
  name    text not null,
  min_xp  integer not null unique,
  reward  text not null
);

create table public.reward_claims (
  user_id      uuid not null references public.profiles(id) on delete cascade,
  level        integer not null references public.levels(level),
  delivered_at timestamptz not null default now(),
  delivered_by uuid,
  primary key (user_id, level)
);

-- ---------------------------------------------------------------------
-- Menú, zona de domicilios y pedidos
-- ---------------------------------------------------------------------
create table public.menu_items (
  id          bigint generated always as identity primary key,
  slug        text not null unique check (slug ~ '^[a-z0-9-]{2,40}$'),
  name        text not null,
  description text not null default '',
  price       integer not null check (price between 1000 and 500000),
  is_burger   boolean not null default true,
  active      boolean not null default true,
  sort        integer not null default 0
);

create table public.delivery_zones (
  barrio  text primary key,
  fee     integer not null default 0 check (fee between 0 and 50000),
  active  boolean not null default true
);

create table public.orders (
  id               uuid primary key default gen_random_uuid(),
  order_no         integer generated always as identity unique,
  user_id          uuid not null references public.profiles(id),
  status           text not null default 'received' check (status in ('received', 'preparing', 'on_the_way', 'ready', 'delivered', 'cancelled')),
  fulfillment      text not null check (fulfillment in ('delivery', 'pickup')),
  barrio           text,
  address          text check (char_length(address) <= 160),
  address_ref      text check (char_length(address_ref) <= 160),
  payment_method   text not null check (payment_method in ('cash', 'transfer', 'card_on_delivery')),
  cash_change_for  integer check (cash_change_for between 0 and 1000000),
  subtotal         integer not null,
  delivery_fee     integer not null,
  total            integer not null,
  notes            text check (char_length(notes) <= 300),
  xp_awarded       boolean not null default false,
  cancelled_reason text check (char_length(cancelled_reason) <= 200),
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index orders_user on public.orders (user_id, created_at desc);
create index orders_status on public.orders (status, created_at);

create table public.order_items (
  order_id     uuid not null references public.orders(id) on delete cascade,
  menu_item_id bigint not null references public.menu_items(id),
  name         text not null,
  unit_price   integer not null,
  qty          integer not null check (qty between 1 and 20),
  primary key (order_id, menu_item_id)
);

-- ---------------------------------------------------------------------
-- Dinámicas: códigos secretos y juego
-- ---------------------------------------------------------------------
create table public.codes (
  id         bigint generated always as identity primary key,
  code_hash  text not null unique,
  label      text not null,
  xp         integer not null check (xp between 1 and 5000),
  max_uses   integer check (max_uses > 0),
  uses       integer not null default 0,
  valid_from timestamptz not null default now(),
