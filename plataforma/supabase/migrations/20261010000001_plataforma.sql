-- ---------------------------------------------------------------------
-- Dinámicas del cliente
-- ---------------------------------------------------------------------
-- Importante: los fallos se devuelven como {ok:false} en vez de lanzar error. Un error desharía
-- también el contador de intentos y la fuerza bruta quedaría sin límite.
create or replace function public.redeem_code(p_code text)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare v public.profiles := app_private.current_profile(); c public.codes;
begin
  perform app_private.rate_limit('code:' || v.id, 10, 3600); -- frena la fuerza bruta
  select * into c from public.codes
   where code_hash = encode(sha256(convert_to(upper(trim(coalesce(p_code, ''))), 'UTF8')), 'hex')
     and active and now() >= valid_from and (valid_to is null or now() <= valid_to)
   for update;
  if not found then return jsonb_build_object('ok', false, 'error', 'CODIGO_INVALIDO'); end if;
  if c.max_uses is not null and c.uses >= c.max_uses then return jsonb_build_object('ok', false, 'error', 'CODIGO_AGOTADO'); end if;
  insert into public.code_redemptions (code_id, user_id) values (c.id, v.id) on conflict do nothing;
  if not found then return jsonb_build_object('ok', false, 'error', 'CODIGO_YA_USADO'); end if;
  update public.codes set uses = uses + 1 where id = c.id;
  perform app_private.grant_xp(v.id, c.xp, 'code', c.id::text);
  return jsonb_build_object('ok', true, 'xp', c.xp, 'label', c.label);
end $$;

-- Juego: empezar una partida gasta una ficha (en el servidor, de forma atómica)
create or replace function public.start_game()
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare v public.profiles := app_private.current_profile(); s public.game_sessions;
begin
  perform pg_advisory_xact_lock(hashtextextended('game:' || v.id::text, 0));
  perform app_private.rate_limit('game:' || v.id, 30, 3600);
  update public.game_sessions set status = 'expired'
   where user_id = v.id and status = 'active' and started_at < now() - interval '3 minutes';
  if exists (select 1 from public.game_sessions where user_id = v.id and status = 'active') then
    raise exception 'PARTIDA_EN_CURSO' using errcode = '55000';
  end if;
  if app_private.ficha_balance(v.id) < 1 then raise exception 'SIN_FICHAS' using errcode = '55000'; end if;
  insert into public.game_sessions (user_id, seed) values (v.id, floor(random() * 2147483647)::int) returning * into s;
  perform app_private.grant_ficha(v.id, -1, 'game', s.id::text);
  return jsonb_build_object('session', s.id, 'seed', s.seed);
end $$;

-- Terminar la partida: el servidor decide cuánta XP vale, con topes y validaciones.
create or replace function public.finish_game(p_session uuid, p_prize text, p_details jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v public.profiles := app_private.current_profile();
  g jsonb := app_private.setting('game');
  s public.game_sessions;
  v_elapsed_ms integer; v_xp integer := 0; v_today integer; v_flag boolean := false;
  v_plush_count integer;
begin
  perform pg_advisory_xact_lock(hashtextextended('game:' || v.id::text, 0));
  select * into s from public.game_sessions where id = p_session and user_id = v.id for update;
  if not found then raise exception 'PARTIDA_NO_EXISTE' using errcode = 'P0002'; end if;
  if s.status <> 'active' then raise exception 'PARTIDA_CERRADA' using errcode = '55000'; end if;

  v_elapsed_ms := (extract(epoch from (now() - s.started_at)) * 1000)::int;
  if v_elapsed_ms > coalesce((g->>'max_duration_ms')::int, 180000) then
    update public.game_sessions set status = 'expired', finished_at = now() where id = s.id;
    return jsonb_build_object('xp', 0, 'expired', true);
  end if;

  if p_prize is not null and not ((g->'xp_by_prize') ? p_prize) then raise exception 'PREMIO_INVALIDO' using errcode = '22023'; end if;
  -- Una partida real con premio dura varios segundos: apuntar, apretar, llevar y soltar.
  if p_prize is not null and v_elapsed_ms < coalesce((g->>'min_duration_ms')::int, 6000) then v_flag := true; end if;
  -- Precisión casi perfecta (< 3 ms del centro) le pasa a una persona ~1 de cada 30 premios.
  -- Tres veces en el mismo día es prácticamente imposible sin un bot: esa partida no da XP y queda marcada.
  if p_prize is not null and jsonb_typeof(p_details->'tap_error_ms') = 'number' and abs((p_details->>'tap_error_ms')::numeric) < 3 then
    if (select count(*) from public.game_sessions
         where user_id = v.id and status = 'finished' and app_private.bogota_date(started_at) = app_private.bogota_date()
           and jsonb_typeof(details->'tap_error_ms') = 'number' and abs((details->>'tap_error_ms')::numeric) < 3) >= 2 then
      v_flag := true;
    end if;
  end if;

  if p_prize is not null and not v_flag then
    select coalesce(sum(amount), 0) into v_today from public.xp_ledger
     where user_id = v.id and reason = 'game' and app_private.bogota_date(created_at) = app_private.bogota_date();
    v_xp := greatest(0, least((g->'xp_by_prize'->>p_prize)::int, coalesce((g->>'daily_xp_cap')::int, 80) - v_today));
    if v_xp > 0 then perform app_private.grant_xp(v.id, v_xp, 'game', s.id::text); end if;

    insert into public.album (user_id, plush, count) values (v.id, p_prize, 1)
    on conflict (user_id, plush) do update set count = public.album.count + 1;
    select count(*) into v_plush_count from public.album where user_id = v.id and count > 0;
    if v_plush_count >= (select count(*) from jsonb_object_keys(g->'xp_by_prize')) then
      perform app_private.grant_xp(v.id, coalesce((g->>'album_bonus')::int, 200), 'album', 'album');
    end if;
  end if;

  update public.game_sessions set status = 'finished', finished_at = now(), prize = p_prize, xp_awarded = v_xp,
         flagged = v_flag, details = jsonb_strip_nulls(p_details) where id = s.id;
  return jsonb_build_object('xp', v_xp, 'flagged', v_flag);
end $$;

