-- =====================================================================
-- Funciones auxiliares privadas
-- =====================================================================
create or replace function app_private.setting(p_key text)
returns jsonb language sql stable security definer set search_path = public, pg_temp as $$
  select value from public.settings where key = p_key
$$;

create or replace function app_private.bogota_date(p_ts timestamptz default now())
returns date language sql immutable as $$
  select (p_ts at time zone 'America/Bogota')::date
$$;

create or replace function app_private.current_profile()
returns public.profiles language plpgsql stable security definer set search_path = public, pg_temp as $$
declare v public.profiles;
begin
  if auth.uid() is null then raise exception 'NO_AUTENTICADO' using errcode = '28000'; end if;
  select * into v from public.profiles where id = auth.uid() and deleted_at is null;
  if not found then raise exception 'PERFIL_INCOMPLETO' using errcode = 'P0002'; end if;
  return v;
end $$;

create or replace function app_private.require_role(p_roles text[])
returns public.profiles language plpgsql stable security definer set search_path = public, pg_temp as $$
declare v public.profiles;
begin
  v := app_private.current_profile();
  if not (v.role = any (p_roles)) then raise exception 'NO_AUTORIZADO' using errcode = '42501'; end if;
  return v;
end $$;

create or replace function app_private.is_staff()
returns boolean language sql stable security definer set search_path = public, pg_temp as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role in ('staff', 'admin') and deleted_at is null)
$$;

-- Limita intentos por llave en una ventana de tiempo. Lanza error si se excede.
create or replace function app_private.rate_limit(p_key text, p_max integer, p_window_seconds integer)
returns void language plpgsql security definer set search_path = public, app_private, pg_temp as $$
declare v app_private.rate_limits;
begin
  insert into app_private.rate_limits as r (key, window_start, hits) values (p_key, now(), 1)
  on conflict (key) do update set
    hits = case when r.window_start < now() - make_interval(secs => p_window_seconds) then 1 else r.hits + 1 end,
    window_start = case when r.window_start < now() - make_interval(secs => p_window_seconds) then now() else r.window_start end
  returning * into v;
  if v.hits > p_max then raise exception 'DEMASIADOS_INTENTOS' using errcode = '54000'; end if;
end $$;

create or replace function app_private.audit(p_action text, p_target text, p_details jsonb)
returns void language sql security definer set search_path = public, pg_temp as $$
  insert into public.audit_log (actor, action, target, details) values (auth.uid(), p_action, p_target, p_details)
$$;

create or replace function app_private.grant_xp(p_user uuid, p_amount integer, p_reason text, p_ref text)
returns boolean language plpgsql security definer set search_path = public, pg_temp as $$
declare v_id bigint;
begin
  if p_amount = 0 then return false; end if;
  insert into public.xp_ledger (user_id, amount, reason, ref, created_by)
  values (p_user, p_amount, p_reason, p_ref, auth.uid())
  on conflict (user_id, reason, ref) do nothing
  returning id into v_id;
  return v_id is not null;
end $$;

create or replace function app_private.grant_ficha(p_user uuid, p_delta integer, p_reason text, p_ref text)
returns boolean language plpgsql security definer set search_path = public, pg_temp as $$
declare v_id bigint;
begin
  insert into public.ficha_ledger (user_id, delta, reason, ref, created_by)
  values (p_user, p_delta, p_reason, p_ref, auth.uid())
  on conflict (user_id, reason, ref) do nothing
  returning id into v_id;
  return v_id is not null;
end $$;

create or replace function app_private.xp_total(p_user uuid)
returns integer language sql stable security definer set search_path = public, pg_temp as $$
  select coalesce(sum(amount), 0)::integer from public.xp_ledger where user_id = p_user
$$;

create or replace function app_private.ficha_balance(p_user uuid)
returns integer language sql stable security definer set search_path = public, pg_temp as $$
  select coalesce(sum(delta), 0)::integer from public.ficha_ledger where user_id = p_user
$$;

-- XP y ficha por una compra (pedido entregado o compra en el local).
-- Reglas en settings.xp. Máximo N compras con XP por día (hora de Bogotá).
create or replace function app_private.award_purchase(p_user uuid, p_burgers integer, p_montaneras integer, p_ref text)
returns integer language plpgsql security definer set search_path = public, pg_temp as $$
declare
  r jsonb := app_private.setting('xp');
  v_today_purchases integer;
  v_total integer := 0;
  v_extra integer;
  v_prof public.profiles;
  v_first boolean;
  v_ref_count integer;
begin
  if p_burgers < 1 then return 0; end if;
  perform pg_advisory_xact_lock(hashtextextended('purchase:' || p_user::text, 0));

  select count(*) into v_today_purchases from public.xp_ledger
   where user_id = p_user and reason = 'purchase' and app_private.bogota_date(created_at) = app_private.bogota_date();
  if v_today_purchases >= coalesce((r->>'purchases_per_day')::int, 1) then return 0; end if;

  select not exists (select 1 from public.xp_ledger where user_id = p_user and reason = 'purchase') into v_first;

  if app_private.grant_xp(p_user, (r->>'purchase')::int, 'purchase', p_ref) then
    v_total := (r->>'purchase')::int;
    v_extra := least(greatest(p_burgers - 1, 0), coalesce((r->>'extra_burger_max')::int, 4));
    if v_extra > 0 and app_private.grant_xp(p_user, v_extra * (r->>'extra_burger')::int, 'extra_burger', p_ref) then
      v_total := v_total + v_extra * (r->>'extra_burger')::int;
    end if;
    if p_montaneras > 0 and app_private.grant_xp(p_user, least(p_montaneras, 20) * (r->>'montanera_bonus')::int, 'montanera_bonus', p_ref) then
      v_total := v_total + least(p_montaneras, 20) * (r->>'montanera_bonus')::int;
    end if;
    perform app_private.grant_ficha(p_user, 1, 'purchase', p_ref);

    -- Referido: el que invitó gana cuando el invitado hace su primera compra con XP
    if v_first then
      select * into v_prof from public.profiles where id = p_user;
      if v_prof.referred_by is not null then
        select count(*) into v_ref_count from public.xp_ledger where user_id = v_prof.referred_by and reason = 'referral';
        if v_ref_count < coalesce((r->>'referral_max')::int, 5) then
          perform app_private.grant_xp(v_prof.referred_by, (r->>'referral')::int, 'referral', p_user::text);
        end if;
      end if;
    end if;
  end if;
  return v_total;
end $$;

