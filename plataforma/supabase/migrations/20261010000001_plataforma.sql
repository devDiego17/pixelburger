-- Borrar la cuenta (derecho de supresión, Ley 1581): se eliminan los datos personales.
create or replace function public.delete_my_account()
returns void language plpgsql security definer set search_path = public, pg_temp as $$
declare v public.profiles := app_private.current_profile();
begin
  update public.profiles set
    display_name = 'Jugador eliminado', alias = 'borrado_' || player_no, whatsapp = null, barrio = null,
    consent_marketing = false, deleted_at = now(), qr_token = replace(gen_random_uuid()::text, '-', '')
  where id = v.id;
  update public.orders set address = null, address_ref = null, notes = null where user_id = v.id;
  perform app_private.audit('delete_account', v.id::text, null);
end $$;

-- Resumen del jugador para la pantalla de inicio
create or replace function public.my_summary()
returns jsonb language plpgsql stable security definer set search_path = public, pg_temp as $$
declare
  v public.profiles := app_private.current_profile();
  v_xp integer := app_private.xp_total(v.id);
  v_level public.levels; v_next public.levels;
  v_rank integer;
begin
  select * into v_level from public.levels where min_xp <= v_xp order by min_xp desc limit 1;
  select * into v_next from public.levels where min_xp > v_xp order by min_xp asc limit 1;
  select rank into v_rank from public.leaderboard(1000) where alias = v.alias;
  return jsonb_build_object(
    'player_no', v.player_no, 'display_name', v.display_name, 'alias', v.alias,
    'whatsapp', v.whatsapp, 'barrio', v.barrio, 'consent_marketing', v.consent_marketing,
    'role', v.role, 'qr_token', v.qr_token,
    'xp', v_xp, 'fichas', app_private.ficha_balance(v.id),
    'level', to_jsonb(v_level), 'next_level', to_jsonb(v_next), 'rank', v_rank,
    'pending_rewards', (select coalesce(jsonb_agg(to_jsonb(l) order by l.level), '[]'::jsonb) from public.levels l
                         where l.min_xp <= v_xp and l.level > 0
                           and not exists (select 1 from public.reward_claims c where c.user_id = v.id and c.level = l.level)),
    'game_xp_today', (select coalesce(sum(amount), 0) from public.xp_ledger where user_id = v.id and reason = 'game' and app_private.bogota_date(created_at) = app_private.bogota_date()),
    'album', (select coalesce(jsonb_object_agg(plush, count), '{}'::jsonb) from public.album where user_id = v.id)
  );
end $$;

-- Ranking de la campaña: solo alias y XP. Desempate: quien llegó primero.
create or replace function public.leaderboard(p_limit integer default 20)
returns table (rank integer, alias text, xp integer)
language sql stable security definer set search_path = public, pg_temp as $$
  with c as (select (value->>'starts_at')::timestamptz as s, (value->>'ends_at')::timestamptz as e from public.settings where key = 'campaign'),
       g as (select coalesce((value->>'counts_for_ranking')::boolean, true) as game_counts from public.settings where key = 'game'),
       t as (
         select p.alias, sum(l.amount)::integer as xp, max(l.created_at) as last_at, min(p.player_no) as pno
         from public.xp_ledger l join public.profiles p on p.id = l.user_id, c, g
         where p.deleted_at is null and p.role = 'customer' and p.adult_confirmed and p.consent_data_at is not null
           and l.created_at between c.s and c.e
           and (g.game_counts or l.reason not in ('game', 'album'))
         group by p.alias
         having sum(l.amount) > 0)
  select (row_number() over (order by xp desc, last_at asc, pno asc))::integer, alias, xp
  from t order by 1 limit least(greatest(p_limit, 1), 1000)
$$;

-- Hacer un pedido: los precios y el domicilio se calculan en el servidor.
create or replace function public.place_order(
  p_items jsonb, p_fulfillment text, p_barrio text, p_address text, p_address_ref text,
  p_payment text, p_cash_change_for integer default null, p_notes text default null)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v public.profiles := app_private.current_profile();
  o jsonb := app_private.setting('orders');
  v_order public.orders;
  v_item jsonb; v_menu public.menu_items;
  v_qty integer; v_total_qty integer := 0; v_subtotal integer := 0; v_fee integer := 0;
  v_open integer;
begin
  perform app_private.rate_limit('order:' || v.id, 3, 600);
  if not coalesce((app_private.setting('store')->>'open')::boolean, true) then raise exception 'TIENDA_CERRADA' using errcode = '55000'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 20 then raise exception 'PEDIDO_INVALIDO' using errcode = '22023'; end if;
  if p_fulfillment not in ('delivery', 'pickup') then raise exception 'PEDIDO_INVALIDO' using errcode = '22023'; end if;
  if p_payment not in ('cash', 'transfer', 'card_on_delivery') then raise exception 'PAGO_INVALIDO' using errcode = '22023'; end if;

  select count(*) into v_open from public.orders where user_id = v.id and status in ('received', 'preparing', 'on_the_way', 'ready');
  if v_open >= coalesce((o->>'max_open')::int, 2) then raise exception 'TIENES_PEDIDOS_ABIERTOS' using errcode = '55000'; end if;

  if p_fulfillment = 'delivery' then
    if coalesce(trim(p_address), '') = '' then raise exception 'FALTA_DIRECCION' using errcode = '22023'; end if;
    select fee into v_fee from public.delivery_zones where barrio = p_barrio and active;
    if not found then raise exception 'FUERA_DE_ZONA' using errcode = '22023'; end if;
  end if;

  insert into public.orders (user_id, fulfillment, barrio, address, address_ref, payment_method, cash_change_for, subtotal, delivery_fee, total, notes)
  values (v.id, p_fulfillment, case when p_fulfillment = 'delivery' then p_barrio end,
          case when p_fulfillment = 'delivery' then trim(p_address) end,
          case when p_fulfillment = 'delivery' then nullif(trim(p_address_ref), '') end,
          p_payment, case when p_payment = 'cash' then p_cash_change_for end, 0, coalesce(v_fee, 0), 0, nullif(trim(p_notes), ''))
  returning * into v_order;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'qty')::int;
    if v_qty is null or v_qty < 1 or v_qty > 20 then raise exception 'CANTIDAD_INVALIDA' using errcode = '22023'; end if;
    select * into v_menu from public.menu_items where slug = v_item->>'slug' and active;
    if not found then raise exception 'PRODUCTO_NO_DISPONIBLE' using errcode = '22023'; end if;
    insert into public.order_items (order_id, menu_item_id, name, unit_price, qty)
    values (v_order.id, v_menu.id, v_menu.name, v_menu.price, v_qty)
    on conflict (order_id, menu_item_id) do update set qty = public.order_items.qty + excluded.qty;
    v_total_qty := v_total_qty + v_qty;
    v_subtotal := v_subtotal + v_menu.price * v_qty;
  end loop;

  if v_total_qty > coalesce((o->>'max_items')::int, 20) then raise exception 'DEMASIADOS_PRODUCTOS' using errcode = '22023'; end if;
  if v_subtotal < coalesce((o->>'min_total')::int, 0) then raise exception 'PEDIDO_MINIMO' using errcode = '22023'; end if;

  update public.orders set subtotal = v_subtotal, total = v_subtotal + coalesce(v_fee, 0) where id = v_order.id
  returning * into v_order;
  return jsonb_build_object('id', v_order.id, 'order_no', v_order.order_no, 'total', v_order.total);
end $$;

