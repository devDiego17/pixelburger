create or replace function public.staff_set_order_status(p_order uuid, p_status text, p_reason text default null)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_staff public.profiles := app_private.require_role(array['staff', 'admin']);
  v_order public.orders;
  v_burgers integer; v_mont integer; v_xp integer := 0;
begin
  select * into v_order from public.orders where id = p_order for update;
  if not found then raise exception 'PEDIDO_NO_EXISTE' using errcode = 'P0002'; end if;
  if v_order.status in ('delivered', 'cancelled') then raise exception 'PEDIDO_CERRADO' using errcode = '55000'; end if;
  if p_status not in ('preparing', 'on_the_way', 'ready', 'delivered', 'cancelled') then raise exception 'ESTADO_INVALIDO' using errcode = '22023'; end if;
  if p_status = 'on_the_way' and v_order.fulfillment <> 'delivery' then raise exception 'ESTADO_INVALIDO' using errcode = '22023'; end if;
  if p_status = 'ready' and v_order.fulfillment <> 'pickup' then raise exception 'ESTADO_INVALIDO' using errcode = '22023'; end if;

  update public.orders set status = p_status, updated_at = now(),
         cancelled_reason = case when p_status = 'cancelled' then coalesce(nullif(trim(p_reason), ''), 'Cancelado por Pixel Burger') end
   where id = p_order;

  if p_status = 'delivered' and not v_order.xp_awarded then
    select coalesce(sum(i.qty) filter (where m.is_burger), 0), coalesce(sum(i.qty) filter (where m.slug = 'montanera'), 0)
      into v_burgers, v_mont
      from public.order_items i join public.menu_items m on m.id = i.menu_item_id where i.order_id = p_order;
    v_xp := app_private.award_purchase(v_order.user_id, v_burgers, v_mont, 'order:' || p_order);
    update public.orders set xp_awarded = true where id = p_order;
  end if;

  perform app_private.audit('order_status', p_order::text, jsonb_build_object('status', p_status, 'xp', v_xp));
  return jsonb_build_object('status', p_status, 'xp', v_xp);
end $$;

